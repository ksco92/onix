def test_wide_interval_components_share_one_null_mask(tmp_path: Path) -> None:
    """`interval_months`/`_days`/`_nanos` are null together, row by row."""
    out = tmp_path / "fixture"
    generate(5000, SEED, out, kind="wide")
    table = pq.read_table(out / "a.parquet")
    months = table.column("interval_months").to_pylist()
    days = table.column("interval_days").to_pylist()
    nanos = table.column("interval_nanos").to_pylist()

    for m, d, n in zip(months, days, nanos, strict=True):
        null_flags = {m is None, d is None, n is None}
        assert len(null_flags) == 1


def test_wide_date64_millis_is_whole_day_aligned(tmp_path: Path) -> None:
    """`date64_millis` values are always a whole number of days, Arrow's `Date64` contract."""
    out = tmp_path / "fixture"
    generate(5000, SEED, out, kind="wide")
    values = pq.read_table(out / "a.parquet").column("date64_millis").to_pylist()
    for value in values:
        if value is not None:
            assert value % 86_400_000 == 0


def test_wide_float_columns_include_nan_and_signed_zero(tmp_path: Path) -> None:
    """`f32`/`f64` occasionally draw NaN and `-0.0`, per the module docstring."""
    out = tmp_path / "fixture"
    generate(5000, SEED, out, kind="wide")
    f64 = pq.read_table(out / "a.parquet").column("f64").to_pylist()
    has_nan = any(v is not None and v != v for v in f64)  # noqa: PLR0124 (NaN self-inequality)
    has_neg_zero = any(v == 0.0 and str(v) == "-0.0" for v in f64 if v is not None)
    assert has_nan
    assert has_neg_zero


@pytest.mark.parametrize("rows", [0, 1])
def test_wide_generate_with_zero_or_one_row(rows: int, tmp_path: Path) -> None:
    """A near-empty `wide` fixture doesn't crash even though every rate rounds to 0."""
    out = tmp_path / "fixture"
    manifest = generate(rows, SEED, out, kind="wide")

    assert manifest["rows_deleted"] == 0
    assert manifest["rows_added"] == 0
    assert pq.read_table(out / "a.parquet").num_rows == rows
