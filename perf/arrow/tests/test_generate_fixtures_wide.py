def test_wide_ts_cast_is_never_null_and_never_independently_modified(tmp_path: Path) -> None:
    """`ts_cast` carries no null and no `value_changed` count of its own."""
    out = tmp_path / "fixture"
    manifest = generate(5000, SEED, out, kind="wide")
    assert "ts_cast" not in manifest["value_changed_per_column"]
    for side in ("a.parquet", "b.parquet"):
        assert None not in pq.read_table(out / side).column("ts_cast").to_pylist()


