def test_wide_regeneration_is_byte_identical(tmp_path: Path) -> None:
    """Two `wide` runs with the same rows/seed produce identical bytes."""
    out1, out2 = tmp_path / "run1", tmp_path / "run2"
    generate(2000, SEED, out1, kind="wide")
    generate(2000, SEED, out2, kind="wide")

    for name in ("a.parquet", "b.parquet", "manifest.json"):
        assert (out1 / name).read_bytes() == (out2 / name).read_bytes()


def test_wide_different_seeds_produce_different_output(tmp_path: Path) -> None:
    """A different seed changes the generated bytes."""
    out1, out2 = tmp_path / "run1", tmp_path / "run2"
    generate(2000, SEED, out1, kind="wide")
    generate(2000, SEED + 1, out2, kind="wide")

    assert (out1 / "a.parquet").read_bytes() != (out2 / "a.parquet").read_bytes()


def test_wide_a_schema_covers_every_documented_type(tmp_path: Path) -> None:
    """`a.parquet`'s schema has exactly the documented columns and types."""
    out = tmp_path / "fixture"
    generate(2000, SEED, out, kind="wide")
    schema = pq.read_schema(out / "a.parquet")

    assert schema.names == list(_EXPECTED_A_TYPES)
    for name, expected_type in _EXPECTED_A_TYPES.items():
        assert str(schema.field(name).type) == expected_type, name


def test_wide_b_schema_has_the_four_schema_changes(tmp_path: Path) -> None:
    """`b.parquet` retypes `category`/`dec_scale4`/`ts_cast` and adds `extra`."""
    out = tmp_path / "fixture"
    generate(2000, SEED, out, kind="wide")
    schema = pq.read_schema(out / "b.parquet")

    assert schema.names == [*_EXPECTED_A_TYPES, "extra"]
    assert str(schema.field("category").type) == "dictionary<values=string, indices=int32, ordered=0>"
    assert str(schema.field("dec_scale4").type) == "decimal128(18, 6)"
    assert str(schema.field("ts_cast").type) == "timestamp[us]"
    assert str(schema.field("extra").type) == "string"


def test_wide_manifest_schema_changes_list_the_four_documented_changes(tmp_path: Path) -> None:
    """The sidecar's `schema_changes` names exactly the four retyped/added columns."""
    manifest = generate(2000, SEED, tmp_path / "fixture", kind="wide")
    changed_columns = {entry["column"] for entry in manifest["schema_changes"]}
    assert changed_columns == {"category", "dec_scale4", "ts_cast", "extra"}


def test_wide_sidecar_counts_match_actual_row_counts(tmp_path: Path) -> None:
    """Every sidecar row count matches what's actually in the parquet files."""
    out = tmp_path / "fixture"
    manifest = generate(5000, SEED, out, kind="wide")

    a = pq.read_table(out / "a.parquet")
    b = pq.read_table(out / "b.parquet")

    assert a.num_rows == 5000
    assert b.num_rows == 5000 - manifest["rows_deleted"] + manifest["rows_added"]
    manifest_on_disk = json.loads((out / "manifest.json").read_text())
    assert manifest_on_disk == manifest


